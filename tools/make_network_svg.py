"""Generate a schematic (not geographic) river-network SVG for the GNN slides.
Deterministic: same seed -> same picture. Usage: python3 tools/make_network_svg.py"""
import math, random, pathlib, json
random.seed(7)
W, H = 900, 760
nodes, edges = [], []          # node: (x, y, order)
def grow(x, y, ang, length, depth, parent):
    nx_, ny_ = x + length*math.cos(ang), y - length*math.sin(ang)
    idx = len(nodes); nodes.append((nx_, ny_, depth)); edges.append((idx, parent))
    if depth <= 0: return
    n = 2 if random.random() < .82 else 1
    for k in range(n):
        da = (random.uniform(.28, .62) * (1 if k == 0 else -1)) if n == 2 else random.uniform(-.25, .25)
        grow(nx_, ny_, ang+da, length*random.uniform(.7, .86), depth-1, idx)
nodes.append((W/2, H-30, 9)); root = 0
grow(W/2, H-30, math.pi/2, 120, 7, root)
xs=[n[0] for n in nodes]; ys=[n[1] for n in nodes]
sx = (W-60)/(max(xs)-min(xs)); sy=(H-60)/(max(ys)-min(ys)); s=min(sx,sy,1)
cx=(max(xs)+min(xs))/2; cy=(max(ys)+min(ys))/2
P=[((x-cx)*s+W/2,(y-cy)*s+H/2,d) for x,y,d in nodes]
# stream order ~ depth: thicker near outlet
bx0=min(q[0] for q in P)-20; by0=min(q[1] for q in P)-20; bx1=max(q[0] for q in P)+20; by1=max(q[1] for q in P)+20
out=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{bx0:.0f} {by0:.0f} {bx1-bx0:.0f} {by1-by0:.0f}">',
 '<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="5" markerHeight="5" orient="auto"><path d="M0 0L10 5L0 10z" fill="#4A86C8"/></marker></defs>']
for c,p in edges:
    x1,y1,d=P[c]; x2,y2,_=P[p]
    w=1.3+d*0.85
    out.append(f'<line class="riv" x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="#4A86C8" stroke-width="{w:.1f}" stroke-linecap="round" opacity=".85"/>')
# animated "water" overlay: dashes travel from upstream (x1) to downstream (x2)
for c,p in edges:
    x1,y1,d=P[c]; x2,y2,_=P[p]
    if d < 1: continue
    w=max(1.2, (1.3+d*0.85)*0.45)
    out.append(f'<line class="flow" x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="#DDF1FF" stroke-width="{w:.1f}" stroke-linecap="round"/>')
for i,(x,y,d) in enumerate(P):
    out.append(f'<circle class="nd" cx="{x:.1f}" cy="{y:.1f}" r="4.2" fill="#B9C2BF"/>')
# gauges: pick a few interior nodes of moderate order
cand=[i for i,(x,y,d) in enumerate(P) if 3<=d<=6]
random.shuffle(cand)
gauges=cand[:4]; held=cand[4:5]
out.append('<g class="gauges">')
for i in gauges:
    x,y,_=P[i]; out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="13" fill="#054A37" stroke="#fff" stroke-width="3"/>')
out.append('</g><g class="held">')
for i in held:
    x,y,_=P[i]; out.append(f'<circle class="pulse" cx="{x:.1f}" cy="{y:.1f}" r="13" fill="#fff" stroke="#B26B00" stroke-width="5" stroke-dasharray="6 4"/>')
out.append('</g>')
x,y,_=P[0]; out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="10" fill="#123B31"/>')
out.append('</svg>')
root=pathlib.Path(__file__).resolve().parent.parent
svg='\n'.join(out)
root.joinpath('assets/img/gnn_network_schematic.svg').write_text(svg)
# same drawing as a JS string, so it can be inlined (and animated) even from file://
root.joinpath('js/network.js').write_text('/* generated by tools/make_network_svg.py */\nwindow.NETWORK_SVG = ' + json.dumps(svg) + ';\n')
print(len(P),'nodes', len(gauges),'gauges')
